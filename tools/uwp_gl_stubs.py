#!/usr/bin/env python3
"""Generate the UWP x86-64 ILP32 (x32) guest's OpenGL ES entry points and host ABI wrappers.

The guest (x86_64-linux-gnux32, System V AMD64 ILP32 ABI) calls hostgl_<function>
through __host_import_table. The 64-bit UWP host (x86_64-pc-windows-msvc, MS x64 ABI)
provides __attribute__((sysv_abi)) wrappers in host_gl_table.c that forward the
arguments to the MS-ABI GL_APIENTRY entry points in libGLESv2.dll / libEGL.dll.

Usage: uwp_gl_stubs.py gl.h gl32.h gl2ext.h guest_gl.c host_gl_table.c imports.list
"""

import re
import sys

# System V AMD64 ABI passes the first 6 integer/pointer arguments in registers
# (rdi, rsi, rdx, rcx, r8, r9).
INTEGER_REGISTER_COUNT = 6
WIDE_TYPES = {"GLsizeiptr", "GLintptr", "GLint64", "GLuint64", "GLint64EXT", "GLuint64EXT"}
FLOAT_TYPES = {"GLfloat", "GLclampf", "GLdouble", "GLclampd", "float", "double"}


def android_functions(gl_header: str):
    text = open(gl_header, encoding="utf-8").read()
    start = text.index("/* ANDROID_GL_FUNCTIONS_BEGIN */")
    end = text.index("/* ANDROID_GL_FUNCTIONS_END */")
    return re.findall(r"X\((\w+)\)", text[start:end])


def prototypes(*headers):
    result = {}
    pattern = re.compile(r"GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(\w+)\s*\((.*?)\);", re.S)
    for header in headers:
        text = open(header, encoding="utf-8").read()
        for ret, name, params in pattern.findall(text):
            params = " ".join(params.split())
            result.setdefault(name, (ret.strip(), params))
    return result


def split_parameter(param: str):
    param = param.strip()
    m = re.match(r"(.*?)(\w+)\s*$", param)
    ptype, pname = m.group(1).strip(), m.group(2)
    if not ptype:
        ptype, pname = param, None
    return ptype, pname


def main():
    gl_header, gl32, gl2ext, guest_output, host_output, imports = sys.argv[1:7]
    functions = android_functions(gl_header)
    protos = prototypes(gl32, gl2ext)

    guest_out = [
        "/* generated by tools/uwp_gl_stubs.py from port/linux/src/gl.h; do not edit */",
        "#include <GLES3/gl32.h>",
        "#include <GLES2/gl2ext.h>",
        "#include <string.h>",
        "",
        "void host_gl_get_string(unsigned int name, int index, char *buffer, unsigned int size);",
        "",
    ]

    host_out = [
        "/* generated by tools/uwp_gl_stubs.py from port/linux/src/gl.h; do not edit */",
        "#include <GLES3/gl32.h>",
        "#include <GLES2/gl2ext.h>",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
        "void *host_gl_resolve(const char *name);",
        "",
    ]

    table = []
    import_names = []
    host_entries = []

    for name in functions:
        if name not in protos:
            raise SystemExit(f"{name}: no prototype in the GLES headers")
        ret, params = protos[name]
        if params in ("void", ""):
            plist = []
        else:
            plist = [split_parameter(p) for p in params.split(",")]

        if name == "glGetString":
            guest_out += [
                "static const GLubyte *GL_APIENTRY guest_glGetString(GLenum name)",
                "{",
                "\tstatic __thread char buffer[4][4096];",
                "\tstatic __thread int next;",
                "\tchar *result = buffer[next++ & 3];",
                "",
                "\thost_gl_get_string(name, -1, result, sizeof(buffer[0]));",
                "\treturn (const GLubyte *)result;",
                "}",
                "",
            ]
            table.append(name)
            continue

        if name == "glShaderSource":
            import_names.append("hostgl_glShaderSource")
            host_entries.append(("hostgl_glShaderSource", "wrap_hostgl_glShaderSource"))
            guest_out += [
                "void hostgl_glShaderSource(GLuint shader, GLsizei count, const unsigned long long *strings, "
                "const GLint *lengths);",
                "static void GL_APIENTRY guest_glShaderSource(GLuint shader, GLsizei count, "
                "const GLchar *const *strings, const GLint *lengths)",
                "{",
                "\tunsigned long long wide[16];",
                "\tGLsizei index;",
                "",
                "\tif (count > 16)",
                "\t\tcount = 16;",
                "\tfor (index = 0; index < count; index++)",
                "\t\twide[index] = (unsigned long long)(unsigned int)strings[index];",
                "\thostgl_glShaderSource(shader, count, wide, lengths);",
                "}",
                "",
            ]
            host_out += [
                "typedef void (GL_APIENTRY *pfn_glShaderSource)(GLuint, GLsizei, const GLchar *const *, const GLint *);",
                "static pfn_glShaderSource real_glShaderSource;",
                "__attribute__((sysv_abi)) static void wrap_hostgl_glShaderSource(GLuint shader, GLsizei count, "
                "const unsigned long long *strings, const GLint *lengths)",
                "{",
                "\tif (!real_glShaderSource)",
                '\t\treal_glShaderSource = (pfn_glShaderSource)host_gl_resolve("glShaderSource");',
                "\tif (real_glShaderSource)",
                "\t\treal_glShaderSource(shader, count, (const GLchar *const *)strings, lengths);",
                "}",
                "",
            ]
            table.append(name)
            continue

        if "*" in ret:
            raise SystemExit(f"{name}: returns a pointer; add a special case")
        if any(p.count("*") > 1 for p, _ in plist):
            raise SystemExit(f"{name}: takes an array of pointers; add a special case")

        decl_params, host_params, call_args = [], [], []
        host_wrap_params, host_real_types, host_real_args = [], [], []
        integer_index = 0
        for index, (ptype, pname) in enumerate(plist):
            arg = f"a{index}"
            decl_params.append(f"{ptype} {arg}")
            host_real_types.append(ptype)
            is_pointer = "*" in ptype
            base = ptype.replace("const", "").strip()
            if base in FLOAT_TYPES and not is_pointer:
                host_params.append(ptype)
                call_args.append(arg)
                host_wrap_params.append(f"{ptype} {arg}")
                host_real_args.append(arg)
                continue
            wide = base in WIDE_TYPES and not is_pointer
            on_stack = integer_index >= INTEGER_REGISTER_COUNT
            integer_index += 1
            if is_pointer:
                if on_stack:
                    host_params.append("unsigned long long")
                    call_args.append(f"(unsigned long long)(unsigned int){arg}")
                    host_wrap_params.append(f"unsigned long long {arg}")
                    host_real_args.append(f"({ptype})(uintptr_t)(uint32_t){arg}")
                else:
                    host_params.append(ptype)
                    call_args.append(arg)
                    host_wrap_params.append(f"uint64_t {arg}")
                    host_real_args.append(f"({ptype})(uintptr_t)(uint32_t){arg}")
            elif wide or on_stack:
                host_params.append("long long")
                call_args.append(f"(long long){arg}")
                host_wrap_params.append(f"long long {arg}")
                host_real_args.append(f"({ptype}){arg}")
            else:
                host_params.append(ptype)
                call_args.append(arg)
                host_wrap_params.append(f"{ptype} {arg}")
                host_real_args.append(arg)

        host_name = "hostgl_" + name
        wrap_name = "wrap_" + host_name
        import_names.append(host_name)
        host_entries.append((host_name, wrap_name))

        guest_out.append(f"{ret} {host_name}({', '.join(host_params) or 'void'});")
        guest_out.append(f"static {ret} GL_APIENTRY guest_{name}({', '.join(decl_params) or 'void'})")
        guest_out.append("{")
        call = f"{host_name}({', '.join(call_args)})"
        guest_out.append(f"\t{'return ' if ret != 'void' else ''}{call};")
        guest_out.append("}")
        guest_out.append("")

        host_out.append(f"typedef {ret} (GL_APIENTRY *pfn_{name})({', '.join(host_real_types) or 'void'});")
        host_out.append(f"static pfn_{name} real_{name};")
        host_out.append(f"__attribute__((sysv_abi)) static {ret} {wrap_name}({', '.join(host_wrap_params) or 'void'})")
        host_out.append("{")
        host_out.append(f"\tif (!real_{name})")
        host_out.append(f'\t\treal_{name} = (pfn_{name})host_gl_resolve("{name}");')
        if ret == "void":
            host_out.append(f"\tif (real_{name})")
            host_out.append(f"\t\treal_{name}({', '.join(host_real_args)});")
        else:
            host_out.append(f"\tif (!real_{name})")
            host_out.append("\t\treturn 0;")
            host_out.append(f"\treturn real_{name}({', '.join(host_real_args)});")
        host_out.append("}")
        host_out.append("")

        table.append(name)

    guest_out.append("static const struct { const char *name; void *function; } guest_gl_functions[] =")
    guest_out.append("{")
    for name in table:
        guest_out.append(f'\t{{ "{name}", (void *)guest_{name} }},')
    guest_out.append("};")
    guest_out.append("")
    guest_out.append("typedef void (*guest_gl_function)(void);")
    guest_out.append("guest_gl_function guest_gl_get_proc_address(const char *name)")
    guest_out.append("{")
    guest_out.append("\tunsigned long index;")
    guest_out.append("")
    guest_out.append("\tfor (index = 0; index < sizeof(guest_gl_functions) / sizeof(guest_gl_functions[0]); index++)")
    guest_out.append("\t{")
    guest_out.append("\t\tif (!strcmp(guest_gl_functions[index].name, name))")
    guest_out.append("\t\t\treturn (guest_gl_function)guest_gl_functions[index].function;")
    guest_out.append("\t}")
    guest_out.append("\treturn 0;")
    guest_out.append("}")

    host_out.append("static const struct { const char *name; void *function; } host_gl_wrappers[] =")
    host_out.append("{")
    for hname, wname in host_entries:
        host_out.append(f'\t{{ "{hname}", (void *){wname} }},')
    host_out.append("};")
    host_out.append("")
    host_out.append("void *host_gl_resolve_wrapper(const char *name)")
    host_out.append("{")
    host_out.append("\tsize_t index;")
    host_out.append("")
    host_out.append("\tfor (index = 0; index < sizeof(host_gl_wrappers) / sizeof(host_gl_wrappers[0]); index++)")
    host_out.append("\t{")
    host_out.append("\t\tif (!strcmp(host_gl_wrappers[index].name, name))")
    host_out.append("\t\t\treturn host_gl_wrappers[index].function;")
    host_out.append("\t}")
    host_out.append("\treturn NULL;")
    host_out.append("}")

    with open(guest_output, "w", encoding="utf-8") as f:
        f.write("\n".join(guest_out) + "\n")
    with open(host_output, "w", encoding="utf-8") as f:
        f.write("\n".join(host_out) + "\n")
    with open(imports, "w", encoding="utf-8") as f:
        f.write("\n".join(import_names) + "\n")


if __name__ == "__main__":
    main()
