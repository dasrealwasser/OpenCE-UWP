#!/usr/bin/env python3
"""Generate the UWP x86-64 ILP32 (x32) guest import stubs and 64-bit host ABI table.

Every function the guest imports from the host gets an x86-64 stub in imports.s
that jumps through __host_import_table[index] (%rip-relative 64-bit indirect jump).

On the host (x86_64-pc-windows-msvc), each imported host_* and hostposix_*
function gets an __attribute__((sysv_abi)) wrapper that zero-extends 32-bit
guest pointers and calls the MS x64 ABI host function.

Usage: uwp_imports.py guest_host.h posix.h host_table.c imports.s list...
"""

import re
import sys


def parse_prototypes(header_path: str):
    text = open(header_path, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"__attribute__\s*\(\([^)]*\)\)", "", text)
    result = {}
    for m in re.finditer(r"^([A-Za-z_][\w\s\*]*?)\b(host_\w+|posix_\w+)\s*\(([^;]*?)\)\s*;", text, re.M | re.S):
        ret = " ".join(m.group(1).split())
        name = m.group(2).strip()
        params = " ".join(m.group(3).split())
        result[name] = (ret, params)
    return result


def split_param(param: str):
    param = param.strip()
    m = re.match(r"(.*?)(\w+)\s*$", param)
    ptype, pname = m.group(1).strip(), m.group(2)
    return ptype, pname


def host_type_map(ptype: str) -> str:
    ptype = re.sub(r"\bposix_ulong\b", "uint32_t", ptype)
    ptype = re.sub(r"\bposix_long\b", "int32_t", ptype)
    return ptype


def main():
    guest_host_h, posix_h, host_table_path, output_s = sys.argv[1:5]
    lists = sys.argv[5:]

    protos = {}
    protos.update(parse_prototypes(guest_host_h))
    protos.update(parse_prototypes(posix_h))

    names = []
    for path in lists:
        for line in open(path, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if line and line not in names:
                names.append(line)

    out_s = [
        "/* generated by tools/uwp_imports.py; do not edit */",
        "\t.text",
    ]
    for index, name in enumerate(names):
        offset = index * 8
        out_s += [
            f"\t.globl {name}",
            f"\t.type {name},@function",
            "\t.p2align 4",
            f"{name}:",
            f"\tjmpq *__host_import_table+{offset}(%rip)",
        ]
    out_s += [
        "\t.section .rodata,\"a\",@progbits",
        "\t.globl __host_import_names",
        "__host_import_names:",
    ]
    out_s += [f'\t.asciz "{name}"' for name in names]
    out_s += [
        "\t.p2align 2",
        "\t.globl __host_import_count",
        "__host_import_count:",
        f"\t.long {len(names)}",
        "\t.data",
        "\t.p2align 3",
        "\t.globl __host_import_table",
        "__host_import_table:",
        f"\t.zero {max(len(names), 1) * 8}",
    ]
    with open(output_s, "w", encoding="utf-8") as f:
        f.write("\n".join(out_s) + "\n")

    host_names = [n for n in names if not n.startswith("hostgl_")]
    table = [
        "/* generated by tools/uwp_imports.py; do not edit */",
        "#include <stdint.h>",
        "#include <string.h>",
        '#include "posix.h"',
        "",
    ]

    wrappers = []
    for n in host_names:
        real_name = "posix_" + n[len("hostposix_"):] if n.startswith("hostposix_") else n
        if real_name not in protos:
            raise SystemExit(f"{real_name}: prototype not found in {guest_host_h} or {posix_h}")
        ret, params = protos[real_name]
        ret = host_type_map(ret)
        if params in ("void", ""):
            plist = []
        else:
            plist = [split_param(p) for p in params.split(",")]

        real_params = []
        wrap_params = []
        call_args = []
        for idx, (ptype, _) in enumerate(plist):
            ptype = host_type_map(ptype)
            arg = f"a{idx}"
            real_params.append(f"{ptype} {arg}")
            if "*" in ptype:
                wrap_params.append(f"uint64_t {arg}")
                call_args.append(f"({ptype})(uintptr_t)(uint32_t){arg}")
            else:
                wrap_params.append(f"{ptype} {arg}")
                call_args.append(arg)

        if not n.startswith("hostposix_"):
            table.append(f"extern {ret} {real_name}({', '.join(real_params) or 'void'});")

        wrap_name = f"wrap_{n}"
        wrappers.append((n, wrap_name))
        table.append(f"__attribute__((sysv_abi)) static {ret} {wrap_name}({', '.join(wrap_params) or 'void'})")
        table.append("{")
        call = f"{real_name}({', '.join(call_args)})"
        if ret == "void":
            table.append(f"\t{call};")
        else:
            table.append(f"\treturn {call};")
        table.append("}")
        table.append("")

    table += [
        "static const struct { const char *name; void *function; } imports[] =",
        "{",
    ]
    for n, w in wrappers:
        table.append(f'\t{{ "{n}", (void *){w} }},')
    table += [
        "};",
        "",
        "void *host_resolve_import(const char *name)",
        "{",
        "\tsize_t index;",
        "",
        "\tfor (index = 0; index < sizeof(imports) / sizeof(imports[0]); index++)",
        "\t{",
        "\t\tif (!strcmp(imports[index].name, name))",
        "\t\t\treturn imports[index].function;",
        "\t}",
        "\treturn NULL;",
        "}",
    ]
    with open(host_table_path, "w", encoding="utf-8") as f:
        f.write("\n".join(table) + "\n")


if __name__ == "__main__":
    main()
